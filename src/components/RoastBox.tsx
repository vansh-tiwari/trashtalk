"use client";

import React, { useState } from "react";
import { BattleComparisonResult } from "@/types";
import { Flame, Trophy, Share2, Copy, Check, Sparkles } from "lucide-react";
import confetti from "canvas-confetti";

interface RoastBoxProps {
  battle: BattleComparisonResult;
}

export default function RoastBox({ battle }: RoastBoxProps) {
  const [copied, setCopied] = useState(false);
  const { roast, player1, player2 } = battle;

  function triggerCelebration() {
    confetti({
      particleCount: 80,
      spread: 70,
      origin: { y: 0.6 },
    });
  }

  function copyToClipboard() {
    const text = `🔥 TrashTalk 2.0 Verdict: ${player1.username} vs ${player2.username}\nWinner: ${roast.winner.username} (${roast.winner.title})\n\n"${roast.winner.punchline}"\n\nCheck out the full AI Roast on TrashTalk!`;
    navigator.clipboard.writeText(text);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  }

  function shareTwitter() {
    const text = `🔥 TrashTalk 2.0 AI Roast: ${player1.username} vs ${player2.username}\nVerdict: ${roast.winner.username} wins!\n"${roast.winner.punchline}"`;
    const url = `https://twitter.com/intent/tweet?text=${encodeURIComponent(text)}`;
    window.open(url, "_blank");
  }

  return (
    <div className="glass-panel-glow p-6 sm:p-8 rounded-3xl border border-pink-500/30 space-y-6">
      {/* Top Banner */}
      <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4 border-b border-gray-800 pb-5">
        <div className="flex items-center gap-3">
          <div className="w-10 h-10 rounded-xl bg-pink-500/10 border border-pink-500/20 flex items-center justify-center text-pink-400">
            <Flame className="w-6 h-6 animate-pulse" />
          </div>
          <div>
            <div className="flex items-center gap-2">
              <h2 className="text-xl font-extrabold text-white tracking-tight">
                AI TrashTalk Commentary
              </h2>
              <span className="text-[11px] font-mono px-2 py-0.5 rounded bg-pink-500/10 text-pink-300 border border-pink-500/20 capitalize">
                {roast.persona.replace("_", " ")}
              </span>
            </div>
            <p className="text-xs text-gray-400 font-mono">
              Unfiltered, algorithmic breakdown generated by Google Gemini
            </p>
          </div>
        </div>

        {/* Action Buttons */}
        <div className="flex items-center gap-2 self-end sm:self-auto">
          <button
            onClick={copyToClipboard}
            className="flex items-center gap-1.5 px-3 py-1.5 rounded-xl bg-gray-800 hover:bg-gray-700 text-xs font-mono text-gray-200 border border-gray-700 transition-colors"
          >
            {copied ? <Check className="w-3.5 h-3.5 text-green-400" /> : <Copy className="w-3.5 h-3.5" />}
            <span>{copied ? "Copied" : "Copy Roast"}</span>
          </button>
          <button
            onClick={shareTwitter}
            className="flex items-center gap-1.5 px-3 py-1.5 rounded-xl bg-[#1DA1F2]/10 hover:bg-[#1DA1F2]/20 text-[#1DA1F2] border border-[#1DA1F2]/20 text-xs font-mono transition-colors"
          >
            <Share2 className="w-3.5 h-3.5" />
            <span>Tweet Roast</span>
          </button>
        </div>
      </div>

      {/* Head-to-Head Roast */}
      <div className="p-4 sm:p-5 rounded-2xl bg-black/40 border border-gray-800/80 space-y-2">
        <span className="text-[11px] font-mono uppercase tracking-wider text-pink-400 font-bold block">
          ⚡ Head-to-Head Overview
        </span>
        <p className="text-sm sm:text-base text-gray-200 leading-relaxed italic">
          &quot;{roast.headToHeadRoast}&quot;
        </p>
      </div>

      {/* Individual Roasts */}
      <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
        {/* Player 1 Roast */}
        <div className="p-4 rounded-xl bg-cyan-950/10 border border-cyan-500/20 space-y-2">
          <span className="text-[11px] font-mono font-bold text-cyan-400 block">
            Target: @{player1.username}
          </span>
          <p className="text-xs sm:text-sm text-gray-300 leading-relaxed">
            {roast.player1Roast}
          </p>
        </div>

        {/* Player 2 Roast */}
        <div className="p-4 rounded-xl bg-pink-950/10 border border-pink-500/20 space-y-2">
          <span className="text-[11px] font-mono font-bold text-pink-400 block">
            Target: @{player2.username}
          </span>
          <p className="text-xs sm:text-sm text-gray-300 leading-relaxed">
            {roast.player2Roast}
          </p>
        </div>
      </div>

      {/* Winner Spotlight */}
      <div
        onMouseEnter={triggerCelebration}
        className="p-5 sm:p-6 rounded-2xl bg-gradient-to-r from-amber-500/10 via-orange-500/10 to-pink-500/10 border border-amber-500/30 flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4"
      >
        <div className="space-y-1">
          <div className="flex items-center gap-2">
            <Trophy className="w-5 h-5 text-amber-400 fill-amber-400" />
            <span className="text-xs font-mono uppercase tracking-widest text-amber-400 font-extrabold">
              The AI Verdict
            </span>
          </div>
          <h4 className="text-xl font-black text-white">
            Winner: <span className="text-amber-300">@{roast.winner.username}</span>{" "}
            <span className="text-xs font-mono font-normal text-gray-400">
              ({roast.winner.title})
            </span>
          </h4>
          <p className="text-xs sm:text-sm text-amber-200/90 font-medium italic">
            &quot;{roast.winner.punchline}&quot;
          </p>
          <p className="text-xs text-gray-400 mt-1">
            <span className="font-semibold text-gray-300">Why they won:</span> {roast.winner.reasoning}
          </p>
        </div>
      </div>
    </div>
  );
}
